//  ClipboardHistoryManager.swift
//  boringNotch
//
//  Recent text clipboard entries, kept in memory only (never written to disk).
//

import AppKit
import Combine
import Defaults

@MainActor
final class ClipboardHistoryManager: ObservableObject {
    static let shared = ClipboardHistoryManager()

    @Published private(set) var items: [String] = []

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private let maxItems = 20

    /// Types password managers set for content that must not be recorded (nspasteboard.org convention).
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private init() {}

    func start() {
        guard timer == nil, Defaults[.clipboardHistoryEnabled] else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { _ in
            Task { @MainActor in ClipboardHistoryManager.shared.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        items.removeAll()
    }

    func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    func remove(_ text: String) {
        items.removeAll { $0 == text }
    }

    func clear() {
        items.removeAll()
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: ignoredTypes),
              let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty
        else { return }

        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > maxItems {
            items.removeLast(items.count - maxItems)
        }
    }
}
